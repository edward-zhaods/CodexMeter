    static func image(for kind: PetKind) -> NSImage {
        if let cached = cache[kind] {
            return cached
        }
        let rows: [String]
        switch kind {
        case .codex:
            rows = codexRows
        case .cursor:
            rows = cursorRows
        case .gemini:
            rows = geminiRows
        case .claude:
            rows = claudeRows
        }
        let sprite = render(rows)
        cache[kind] = sprite
        return sprite
    }

    static func statusBarImage(moods: [PetKind: PetMood], bob: Bool) -> NSImage {
        let height: CGFloat = 18
        let gap: CGFloat = 3
        let pets = PetKind.allCases
        let icons = pets.map { Self.image(for: $0) }
        let widths = icons.map { icon -> CGFloat in
            let size = icon.size
            guard size.height > 0 else { return height }
            return height * size.width / size.height
        }
        let width = widths.reduce(0, +) + gap * CGFloat(max(0, pets.count - 1))
        let canvasHeight = height + 2
        let scale = NSScreen.main?.backingScaleFactor ?? 2
        guard let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil,
            pixelsWide: max(1, Int((width * scale).rounded(.up))),
            pixelsHigh: max(1, Int((canvasHeight * scale).rounded(.up))),
            bitsPerSample: 8,
            samplesPerPixel: 4,
            hasAlpha: true,
            isPlanar: false,
            colorSpaceName: .deviceRGB,
            bytesPerRow: 0,
            bitsPerPixel: 0
        ) else {
            return NSImage(size: NSSize(width: width, height: canvasHeight))
        }
        rep.size = NSSize(width: width, height: canvasHeight)
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        NSGraphicsContext.current?.imageInterpolation = .none
        var x: CGFloat = 0
        for (index, kind) in pets.enumerated() {
            let mood = moods[kind] ?? .idle
            let yOffset: CGFloat = bob && mood == .working ? 1 : 0
            let rect = NSRect(x: x, y: yOffset, width: widths[index], height: height)
            let fraction: CGFloat = mood == .offline ? 0.38 : 1
            icons[index].draw(in: rect, from: NSRect.zero, operation: NSCompositingOperation.sourceOver, fraction: fraction)
            x += widths[index] + gap
        }
        NSGraphicsContext.restoreGraphicsState()
        let composed = NSImage(size: rep.size)
        composed.addRepresentation(rep)
        composed.isTemplate = false
        return composed
    }

    private static func render(_ rows: [String]) -> NSImage {
        let height = rows.count
        let width = rows[0].split(separator: " ").count
        let size = NSSize(width: width, height: height)
        let sprite = NSImage(size: size)
        sprite.lockFocus()
        NSGraphicsContext.current?.imageInterpolation = .none
        for (y, line) in rows.enumerated() {
            let values = line.split(separator: " ")
            for (x, token) in values.enumerated() {
                let value = Int(token, radix: 16) ?? 0
                guard value > 0 else { continue }
                let rgb = palette[value - 1]
                let red = CGFloat((rgb >> 16) & 0xFF) / 255
                let green = CGFloat((rgb >> 8) & 0xFF) / 255
                let blue = CGFloat(rgb & 0xFF) / 255
                NSColor(srgbRed: red, green: green, blue: blue, alpha: 1).setFill()
                NSRect(x: x, y: height - 1 - y, width: 1, height: 1).fill()
            }
        }
        sprite.unlockFocus()
        sprite.isTemplate = false
        return sprite
    }
